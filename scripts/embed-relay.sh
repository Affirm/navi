#!/bin/bash
# Regenerate Sources/NaviCore/RelaySource.generated.swift from hooks/relay.py.
# Navi sends this embedded copy to remote hosts over SSH, so the server always
# runs the relay that matches the app. RelaySourceTests fails if the two drift.
set -euo pipefail

DIR="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$DIR/hooks/relay.py"
OUT="$DIR/Sources/NaviCore/RelaySource.generated.swift"

# The source is embedded in a #"""..."""# raw string; refuse content that
# would terminate it or interpolate.
if grep -q '"""#' "$SRC" || grep -qF '\#' "$SRC"; then
    echo "relay.py contains '\"\"\"#' or '\\#', which can't be embedded" >&2
    exit 1
fi

{
    echo '// GENERATED by scripts/embed-relay.sh from hooks/relay.py. Do not edit.'
    echo '// swiftlint:disable all'
    echo ''
    echo 'public enum RelaySource {'
    echo '    public static let python = #"""'
    cat "$SRC"
    echo '"""#'
    echo '}'
} > "$OUT"
echo "wrote $OUT" >&2
